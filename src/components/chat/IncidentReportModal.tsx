import { useState } from "react";
import { FileText, Download, Copy, Check, ShieldCheck } from "lucide-react";
import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
  DialogTrigger,
} from "@/components/ui/dialog";
import type { ChatMessage } from "@/lib/chat-client";
import { toast } from "sonner";

export function IncidentReportModal({
  messages,
  onRequestSummary,
}: {
  messages: ChatMessage[];
  onRequestSummary: () => void;
}) {
  const [open, setOpen] = useState(false);
  const [copied, setCopied] = useState(false);

  // Generate markdown report from messages
  const userMessages = messages.filter((m) => m.role === "user");
  const assistantMessages = messages.filter((m) => m.role === "assistant" && m.id !== "greeting");

  const incidentId = `INC-${new Date().getFullYear()}-${Math.floor(1000 + Math.random() * 9000)}`;
  const dateStr = new Date().toISOString().replace("T", " ").slice(0, 19) + " UTC";

  const reportMarkdown = `# CyberShield SOC Incident Triage Report
**Incident ID:** ${incidentId}
**Timestamp:** ${dateStr}
**Analyst:** Riya (CyberShield AI SOC Division)
**Status:** Triaged & Remediated

---

## 1. Executive Summary
During an interactive triage session, the user submitted cybersecurity inquiries and potential security anomalies for automated verification.

- **Total Inquiries Triaged:** ${userMessages.length}
- **Primary Concerns Raised:**
${userMessages.slice(-3).map((m) => `  - "${m.content.slice(0, 100)}..."`).join("\n") || "  - No user inquiries submitted yet."}

---

## 2. Threat Analysis & Indicators
- **Attack Vector:** Social Engineering / Suspected Phishing / Web Exploitation
- **Assessment Findings:**
${assistantMessages.slice(-2).map((m) => `  - ${m.content.slice(0, 140)}...`).join("\n") || "  - Awaiting telemetry."}

---

## 3. Recommended Remediation
1. Verify sender authenticity through out-of-band communication.
2. Invalidate compromised session tokens or credentials if entered.
3. Block suspicious domains on perimeter DNS and firewall filters.
4. Report event to internal SOC and security awareness team.

*Generated by CyberShield AI (Team CODE NEXUS - MASQUERADE '26)*
`;

  const copyReport = async () => {
    try {
      await navigator.clipboard.writeText(reportMarkdown);
      setCopied(true);
      toast.success("Incident report copied to clipboard!");
      setTimeout(() => setCopied(false), 2000);
    } catch {
      toast.error("Failed to copy report");
    }
  };

  const downloadReport = () => {
    try {
      const blob = new Blob([reportMarkdown], { type: "text/markdown" });
      const url = URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = `Incident-Report-${incidentId}.md`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
      toast.success("Incident report downloaded!");
    } catch {
      toast.error("Failed to download file");
    }
  };

  return (
    <Dialog open={open} onOpenChange={setOpen}>
      <DialogTrigger asChild>
        <Button
          variant="outline"
          size="sm"
          className="gap-2 font-mono text-xs border-border/80 hover:border-primary/50"
        >
          <FileText className="size-3.5 text-primary" />
          <span>Incident Report</span>
        </Button>
      </DialogTrigger>
      <DialogContent className="sm:max-w-xl bg-card/95 backdrop-blur-xl border-border">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2">
            <ShieldCheck className="size-5 text-primary" />
            SOC Incident Triage Report
          </DialogTitle>
          <DialogDescription className="text-xs text-muted-foreground">
            Structured security documentation generated from your conversation with Riya.
          </DialogDescription>
        </DialogHeader>

        <div className="space-y-3 py-2">
          <div className="max-h-72 overflow-y-auto rounded-xl border border-border/70 bg-surface/60 p-4 font-mono text-xs text-foreground/90 whitespace-pre-wrap scrollbar-cyber leading-relaxed">
            {reportMarkdown}
          </div>
        </div>

        <DialogFooter className="flex sm:justify-between items-center flex-wrap gap-2">
          <Button
            type="button"
            variant="outline"
            size="sm"
            onClick={() => {
              onRequestSummary();
              setOpen(false);
            }}
            className="font-mono text-xs gap-1.5"
          >
            Ask Riya for Custom Triage in Chat
          </Button>

          <div className="flex gap-2">
            <Button
              type="button"
              variant="secondary"
              size="sm"
              onClick={copyReport}
              className="font-mono text-xs gap-1.5"
            >
              {copied ? <Check className="size-3.5 text-success" /> : <Copy className="size-3.5" />}
              <span>{copied ? "Copied" : "Copy"}</span>
            </Button>
            <Button
              type="button"
              size="sm"
              onClick={downloadReport}
              className="font-mono text-xs gap-1.5"
            >
              <Download className="size-3.5" />
              <span>Download .md</span>
            </Button>
          </div>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
